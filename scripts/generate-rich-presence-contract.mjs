import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const quote = value => JSON.stringify(value)
const title = value => value[0].toUpperCase() + value.slice(1)

export function renderRichPresenceContract(root = projectRoot) {
  const input = readFileSync(join(root, 'src', 'shared', 'rich-presence-contract.json'), 'utf8')
  const value = JSON.parse(input)
  const constants = ['catalog', 'render', 'presence', 'transport'].flatMap(stage => Object.entries(value[stage]).map(([key, number]) => {
    if (!Number.isSafeInteger(number) || number < 0 || number > 2147483647) throw new Error('Invalid rich presence contract limit')
    return `    internal const int ${title(stage)}${title(key)} = ${number};`
  })).join('\n')
  return `// Generated by scripts/generate-rich-presence-contract.mjs. Do not edit.
// Contract SHA256: ${createHash('sha256').update(JSON.stringify(value)).digest('hex')}
using System;
using System.Collections.Generic;
using System.Text;
using System.Text.RegularExpressions;

internal static class RichPresenceContract
{
${constants}
    internal const int LookupSteamResultMin = ${value.lookup.steamResultMin};
    internal const int LookupSteamResultMax = ${value.lookup.steamResultMax};
    internal static readonly string[] Languages = new string[] { ${value.lookup.languages.map(quote).join(', ')} };
    internal static readonly string[] CatalogCodes = new string[] { ${value.lookup.catalogCodes.map(quote).join(', ')} };
    internal static readonly HashSet<string> NativeReadableKeys = new HashSet<string>(new string[] { ${value.fieldPolicy.nativeReadableKeys.map(quote).join(', ')} }, StringComparer.Ordinal);
    internal static readonly Regex Parameter = new Regex(${quote('\\A[' + value.syntax.parameter + ']{1,' + value.presence.keyAsciiLength + '}\\z')}, RegexOptions.CultureInvariant);
    internal static readonly Regex DisplayToken = new Regex(${quote('\\A#[' + value.syntax.displayToken + ']{1,' + value.presence.displayTokenBodyLength + '}\\z')}, RegexOptions.CultureInvariant);
    private static readonly Regex Sensitive = new Regex(${quote(value.fieldPolicy.sensitive)}, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly HashSet<string> Forbidden = new HashSet<string>(new string[] { ${value.fieldPolicy.forbidden.map(quote).join(', ')} }, StringComparer.OrdinalIgnoreCase);
    private static readonly HashSet<string> Exceptions = new HashSet<string>(new string[] { ${value.fieldPolicy.exceptions.map(quote).join(', ')} }, StringComparer.OrdinalIgnoreCase);
    private static readonly UTF8Encoding Utf8 = new UTF8Encoding(false, true);
    internal static bool IsParameter(string key)
    {
        return key != null && Parameter.IsMatch(key) && !Forbidden.Contains(key) && (Exceptions.Contains(key) || !Sensitive.IsMatch(key));
    }
    internal static bool IsWellFormedText(string text)
    {
        if (text == null) return false;
        for (int index = 0; index < text.Length; index++)
        {
            char character = text[index];
            if (Char.IsControl(character) || character == '\\u2028' || character == '\\u2029') return false;
            if (Char.IsHighSurrogate(character)) { if (++index >= text.Length || !Char.IsLowSurrogate(text[index])) return false; }
            else if (Char.IsLowSurrogate(character)) return false;
        }
        return true;
    }
    internal static bool IsText(string text, int maximumBytes)
    {
        return IsWellFormedText(text) && Utf8.GetByteCount(text) <= maximumBytes;
    }
}
`
}

export function checkRichPresenceContract(root = projectRoot) {
  const target = join(root, 'scripts', 'rich-presence-contract.generated.cs')
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== renderRichPresenceContract(root)) throw new Error('Rich presence generated contract is stale; run node scripts/generate-rich-presence-contract.mjs')
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  if (process.argv.length === 3 && process.argv[2] === '--check') checkRichPresenceContract()
  else if (process.argv.length === 2) writeFileSync(join(projectRoot, 'scripts', 'rich-presence-contract.generated.cs'), renderRichPresenceContract())
  else throw new Error('Usage: node scripts/generate-rich-presence-contract.mjs [--check]')
}
